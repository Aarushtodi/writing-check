#!/usr/bin/env python3.12
"""Clipboard watcher. When you copy prose, runs the fast local checker (Vale + Harper, no Claude, no network)
and sends one notification if real errors are found. Only reads text you copy. Never keystrokes.
Pause: touch ~/.writing_watch_off   Resume: rm ~/.writing_watch_off"""
import time, subprocess, os, re, json, tempfile
from AppKit import NSPasteboard
D=os.path.expanduser('~/writing-tools'); OFF=os.path.expanduser('~/.writing_watch_off')
pb=NSPasteboard.generalPasteboard(); last=pb.changeCount()
SKIP_TYPES={'org.nspasteboard.ConcealedType','org.nspasteboard.TransientType','org.nspasteboard.AutoGeneratedType','com.agilebits.onepassword'}
def looks_like_prose(t):
    w=t.split()
    if not (8<=len(w)<=3000): return False
    if re.match(r'^\s*(https?://|/|~|\$ |sudo |cd |curl )',t): return False
    if re.search(r'[{};=<>]{3,}|def |import |function\(|</?\w+>',t): return False
    if sum(c.isalpha() or c.isspace() for c in t)/len(t)<0.85: return False
    return True
def quick_check(text):
    f=tempfile.mktemp(suffix='.md'); open(f,'w').write(text)
    n=0; kinds=set()
    v=subprocess.run([f'{D}/bin/vale','--config',f'{D}/.vale.ini','--output=JSON','--minAlertLevel=error',f],capture_output=True,text=True).stdout
    try:
        for _,al in json.loads(v).items():
            for a in al: n+=1; kinds.add('dashes' if 'Dash' in a['Check'] else 'style')
    except Exception: pass
    h=subprocess.run([f'{D}/bin/harper-cli','lint','--format','compact',f],capture_output=True,text=True).stdout
    for line in h.splitlines():
        if re.match(r'.*?:\d+:\d+: ',line): n+=1; kinds.add('spelling/grammar')
    os.remove(f); return n,kinds
while True:
    time.sleep(1.0)
    c=pb.changeCount()
    if c==last: continue
    last=c
    if os.path.exists(OFF): continue
    types=set(str(t) for t in (pb.types() or []))
    if types & SKIP_TYPES: continue
    t=pb.stringForType_('public.utf8-plain-text')
    if not t or not looks_like_prose(t): continue
    try: n,kinds=quick_check(t)
    except Exception as e: print('check failed',e,flush=True); continue
    print(time.strftime('%H:%M:%S'),'checked',len(t.split()),'words,',n,'issues',flush=True)
    if n:
        msg=f"{n} issue{'s' if n>1 else ''} in what you copied ({', '.join(sorted(kinds))}). Press Cmd+Option+Ctrl+F to fix."
        subprocess.run(['osascript','-e',f'display notification "{msg}" with title "Writing check"'])
